let fruits = [] // fruits is an array that can hold multiple values
fruits[0] = "Apple"
fruits[1] = "Banana"
fruits[2] = "Cherry"

console.log(fruits[0]) // Output: Apple
console.log(fruits[1]) // Output: Banana
console.log(fruits[2]) // Output: Cherry

// You can also create an array with values directly
let colors = ["Red", "Green", "Blue"]   
console.log(colors[0]) // Output: Red
console.log(colors[1]) // Output: Green
console.log(colors[2]) // Output: Blue

// Arrays can hold different types of data
let mixedArray = [42, "Hello", true, null]
console.log(mixedArray[0]) // Output: 42    
console.log(mixedArray[1]) // Output: Hello
console.log(mixedArray[2]) // Output: true
console.log(mixedArray[3]) // Output: null

// You can also use the length property to find out how many items are in the array
console.log(fruits.length) // Output: 3
console.log(colors.length) // Output: 3
console.log(mixedArray.length) // Output: 4 

