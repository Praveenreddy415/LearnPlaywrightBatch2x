// Arithmetic Operators in JavaScript
// =====================================

let a = 10;
let b = 3;

// 1. Addition (+)
let add = a + b;
console.log("Addition:", add);        // 13

// 2. Subtraction (-)
let sub = a - b;
console.log("Subtraction:", sub);     // 7

// 3. Multiplication (*)
let mul = a * b;
console.log("Multiplication:", mul);  // 30

// 4. Division (/)
let div = a / b;
console.log("Division:", div);        // 3.3333...

// 5. Modulus (%) - remainder after division
let mod = a % b;
console.log("Modulus:", mod);         // 1

// 6. Exponentiation (**) - power
let exp = a ** b;
console.log("Exponentiation:", exp);  // 1000  (10^3)

// 7. Increment (++) - increase by 1
let x = 5;
x++;
console.log("Increment:", x);         // 6

// 8. Decrement (--) - decrease by 1
let y = 5;
y--;
console.log("Decrement:", y);         // 4
